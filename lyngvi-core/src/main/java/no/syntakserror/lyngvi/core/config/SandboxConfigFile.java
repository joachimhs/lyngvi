package no.syntakserror.lyngvi.core.config;

import java.io.IOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.nio.file.StandardCopyOption;
import java.util.ArrayList;
import java.util.HashSet;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Map;
import java.util.Optional;
import java.util.Set;
import no.syntakserror.lyngvi.core.api.ErrorCode;
import no.syntakserror.lyngvi.core.api.SandboxException;

/** Reads and writes {@code sandbox.config} (key=value, one per line, {@code #} comments). */
public final class SandboxConfigFile {

    private static final String HEADER = "# Generated by lyngvi; edit with 'setup.sh repo|resources|agent'.";

    private SandboxConfigFile() {}

    /** True for a 1.1.2 {@code sandbox.config}: present, but without {@code SCHEMA_VERSION}. */
    public static boolean needsMigration(Path file) {
        if (!Files.isRegularFile(file)) return false;
        try {
            return Files.readAllLines(file).stream().noneMatch(l -> l.strip().startsWith("SCHEMA_VERSION="));
        } catch (IOException e) {
            return false;
        }
    }

    public static SandboxConfig read(Path file) {
        List<String> lines;
        try {
            lines = Files.readAllLines(file, StandardCharsets.UTF_8);
        } catch (IOException e) {
            throw new SandboxException(ErrorCode.NOT_INITIALIZED, "Cannot read " + file + ": " + e.getMessage(),
                    Map.of("file", file.toString()));
        }
        Map<String, String> kv = new LinkedHashMap<>();
        List<RepoEntry> repos = new ArrayList<>();
        for (String raw : lines) {
            String line = raw.strip();
            if (line.isEmpty() || line.startsWith("#")) continue;
            int eq = line.indexOf('=');
            if (eq <= 0) {
                throw invalid("Malformed line in " + file + ": '" + raw + "'", "line", raw);
            }
            String key = line.substring(0, eq).strip();
            String value = line.substring(eq + 1).strip();
            if (key.equals("REPO")) {
                try {
                    repos.add(RepoEntry.parse(value));
                } catch (IllegalArgumentException e) {
                    throw invalid(e.getMessage() + " in " + file, "line", raw);
                }
            } else {
                kv.put(key, value);
            }
        }
        int schema = kv.containsKey("SCHEMA_VERSION") ? parseInt(kv, "SCHEMA_VERSION") : 1;
        if (schema != SandboxConfig.CURRENT_SCHEMA_VERSION) {
            throw new SandboxException(ErrorCode.NOT_INITIALIZED,
                    file + " has schema version " + schema + "; run 'setup.sh migrate' to upgrade it",
                    Map.of("file", file.toString(), "schemaVersion", schema, "code", "MIGRATION_REQUIRED"));
        }
        Set<String> names = new HashSet<>();
        for (RepoEntry r : repos) {
            if (!names.add(r.name())) {
                throw invalid("Duplicate repository name '" + r.name() + "' in " + file, "name", r.name());
            }
        }
        // Report missing keys in the order they appear in a written file.
        int uid = parseInt(kv, "UID");
        int gid = parseInt(kv, "GID");
        Path profilePack = Path.of(require(kv, "PROFILE", file));
        ResourceLimits limits = new ResourceLimits(
                require(kv, "MEM_LIMIT", file), require(kv, "MEMSWAP_LIMIT", file),
                require(kv, "CPUS", file), require(kv, "PIDS_LIMIT", file));
        List<String> bad = limits.invalidFields();
        if (!bad.isEmpty()) {
            throw invalid("Invalid resource value for " + String.join(", ", bad) + " in " + file, "field", bad.getFirst());
        }
        return new SandboxConfig(
                schema,
                uid,
                gid,
                profilePack,
                Optional.ofNullable(kv.get("SUBNET_PREFIX")).filter(s -> !s.isBlank()),
                limits,
                require(kv, "DEFAULT_AGENT", file),
                require(kv, "LANG_UI", file),
                repos);
    }

    /** Writes the whole file atomically (temp file + atomic move). */
    public static void write(Path file, SandboxConfig c) {
        List<String> lines = new ArrayList<>();
        lines.add(HEADER);
        lines.add("SCHEMA_VERSION=" + c.schemaVersion());
        lines.add("UID=" + c.uid());
        lines.add("GID=" + c.gid());
        lines.add("PROFILE=" + c.profilePack());
        c.subnetPrefix().ifPresent(p -> lines.add("SUBNET_PREFIX=" + p));
        lines.add("MEM_LIMIT=" + c.resources().mem());
        lines.add("MEMSWAP_LIMIT=" + c.resources().memswap());
        lines.add("CPUS=" + c.resources().cpus());
        lines.add("PIDS_LIMIT=" + c.resources().pids());
        lines.add("DEFAULT_AGENT=" + c.defaultAgent());
        lines.add("LANG_UI=" + c.language());
        for (RepoEntry r : c.repos()) {
            lines.add("REPO=" + r.format());
        }
        AtomicFiles.write(file, String.join("\n", lines) + "\n");
    }

    private static String require(Map<String, String> kv, String key, Path file) {
        String v = kv.get(key);
        if (v == null || v.isBlank()) {
            throw invalid("Missing " + key + " in " + file, "key", key);
        }
        return v;
    }

    private static int parseInt(Map<String, String> kv, String key) {
        String v = kv.get(key);
        if (v == null || v.isBlank()) throw invalid("Missing " + key, "key", key);
        try {
            return Integer.parseInt(v);
        } catch (NumberFormatException e) {
            throw invalid(key + " must be an integer, got '" + v + "'", "key", key);
        }
    }

    private static SandboxException invalid(String message, String key, Object value) {
        return new SandboxException(ErrorCode.VALIDATION_FAILED, message, Map.of(key, value));
    }

    /** Small helper shared by config writers. */
    static final class AtomicFiles {
        private AtomicFiles() {}

        static void write(Path file, String content) {
            try {
                Path dir = file.toAbsolutePath().getParent();
                Files.createDirectories(dir);
                Path tmp = Files.createTempFile(dir, "." + file.getFileName(), ".tmp");
                Files.writeString(tmp, content, StandardCharsets.UTF_8);
                Files.move(tmp, file, StandardCopyOption.REPLACE_EXISTING, StandardCopyOption.ATOMIC_MOVE);
            } catch (IOException e) {
                throw new SandboxException(ErrorCode.INTERNAL, "Cannot write " + file + ": " + e.getMessage(), e);
            }
        }
    }
}
